"""Builds data/names.json: official names players type in chat (playable races, reputations,
crafting materials, potions, elixirs, flasks, bandages, bags), in every client language, from
the WoW Forever game tables exported by wago.tools.

Usage: python build/build_names.py [build]

Like places.json, each entry is a concept: any language's name is recognised and shown in the
reader's language ("Linen Cloth" -> "Étoffe de lin" for a French reader). Class and profession
names are in glossary.json (with their slang forms), and places in places.json.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_places import BUILD, LOCALES, fetch  # noqa: E402

OUTPUT = Path(__file__).resolve().parent.parent / "data" / "names.json"
PLACES = OUTPUT.with_name("places.json")
GLOSSARY = OUTPUT.with_name("glossary.json")

PLAYABLE_RACES = {"1", "2", "3", "4", "5", "6", "7", "8"}
# Item kinds typed in trade chat: (class, subclass) of the Item table.
ITEM_KINDS = {("7", sub) for sub in map(str, range(0, 20))} | {("0", "1"), ("0", "2"), ("0", "3"), ("0", "7"),
                                                                 ("1", "0")}
JUNK_RE = re.compile(r"deprecated|unused|test|waylaid supplies|\[|<|\(|monster|qa |\bph\b|zzold|^old |dnd|npc|nyi|copy of",
                     re.IGNORECASE)
# One-word names that are everyday words: masking them would only cost the model the context.
COMMON = {"bleach", "coal", "salt", "bone", "bones", "feather", "jade", "pearl", "ruby", "diamond", "gold", "silver",
          "copper", "iron", "tin", "oil", "wool", "silk", "leather", "cloth", "fish", "meat", "egg", "eggs", "milk",
          "water", "thread", "dye", "flux", "spices", "skin", "scale", "scales", "hide", "fang", "claw", "heart",
          "eye", "tooth", "wing", "tail", "horn", "dust", "essence", "stone", "rock", "wood", "sand", "ash",
          "ink", "parchment", "rope", "vial", "flask", "bag", "pouch", "sack", "box", "knife", "bandage"}


def _clean(name):
    return re.sub(r"\s+", " ", name or "").strip()


def collect(build):
    entries = []          # [{lang: name}]

    races = {lang: fetch("ChrRaces", loc, build) for lang, loc in LOCALES.items()}
    for ident in PLAYABLE_RACES:
        entries.append({lang: _clean(rows.get(ident, {}).get("Name_lang")) for lang, rows in races.items()})

    factions = {lang: fetch("Faction", loc, build) for lang, loc in LOCALES.items()}
    for ident, row in factions["en"].items():
        name = row.get("Name_lang", "")
        # Reputations only, not their groups ("Blacksmithing - Armorsmithing", "PvP Rank Points").
        if row.get("ReputationIndex", "-1") not in ("-1", "") and not JUNK_RE.search(name) \
                and " - " not in name and "points" not in name.lower():
            entries.append({lang: _clean(rows.get(ident, {}).get("Name_lang")) for lang, rows in factions.items()})

    kinds = fetch("Item", "enUS", build)
    wanted = {ident for ident, row in kinds.items() if (row["ClassID"], row["SubclassID"]) in ITEM_KINDS}
    items = {lang: fetch("ItemSparse", loc, build) for lang, loc in LOCALES.items()}
    for ident in sorted(wanted & set(items["en"]), key=int):
        name = items["en"][ident].get("Display_lang", "")
        if not name or JUNK_RE.search(name) or items["en"][ident].get("OverallQualityID") in ("0", "5", "6", "7"):
            continue
        entries.append({lang: _clean(rows.get(ident, {}).get("Display_lang")) for lang, rows in items.items()})
    return entries


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else BUILD
    taken = set()
    for path in (PLACES, GLOSSARY):
        data = json.loads(path.read_text(encoding="utf-8"))
        for concept in data.get("concepts", []):
            taken.update(v.lower() for k, v in concept.items() if isinstance(v, str))
            taken.update(f.lower() for f in concept.get("forms", []))
        taken.update(t.lower() for t in data.get("keep", []))

    result, seen = [], set()
    for entry in collect(build):
        values = {lang: name for lang, name in entry.items() if name}
        english = values.get("en", "")
        key = english.lower()
        if not english or key in seen or key in taken:
            continue                   # duplicate, or already a place or a glossary word
        if " " not in english and key in COMMON:
            continue
        seen.add(key)
        # Italian has no client in WoW Forever: its name is the English one; no duplicate forms.
        result.append({**{lang: name for lang, name in values.items() if lang == "en" or name != english},
                       "forms": []})

    OUTPUT.write_text(json.dumps({
        "_source": f"WoW Forever build {build}: ChrRaces, Faction, Item and ItemSparse tables (wago.tools). "
                   "Generated by build/build_names.py.",
        "concepts": result,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(result)} names written to {OUTPUT}")


if __name__ == "__main__":
    main()
